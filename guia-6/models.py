from typing import Any, Dict, List, Literal

from pydantic import BaseModel, ConfigDict, Field


class ProductoBase(BaseModel):
    """Common fields to create or update a product."""
    nombre: str = Field(..., min_length=1, description="Product name (required)")
    categoria: str = Field(..., min_length=1, description="Product category")
    precio: float = Field(..., gt=0, description="Product price (must be greater than 0)")
    stock: int = Field(..., ge=0, description="Units available (cannot be negative)")


class ProductoCrear(ProductoBase):
    """Data required to create a product. The client assigns the id."""
    id: int = Field(..., description="Unique product identifier")


class ProductoActualizar(ProductoBase):
    """Data to update an existing product (the id comes from the URL)."""


class Producto(ProductoBase):
    """Full representation of a stored product."""
    id: int = Field(..., description="Unique product identifier")

    model_config = ConfigDict(
        json_schema_extra={
            "example": {"id": 1, "nombre": "Laptop", "categoria": "Tecnología", "precio": 2500000, "stock": 10}
        }
    )


class ErrorResponse(BaseModel):
    """Standard error body returned by the API."""
    detail: str = Field(..., description="Human-readable error message")


class ValidationErrorResponse(ErrorResponse):
    """Error body returned when the request data is invalid or incomplete."""
    errors: List[Dict[str, Any]] = Field(..., description="Validation errors reported for each invalid field")


class AIConsulta(BaseModel):
    """Request body for the AI endpoint."""
    pregunta: str = Field(..., min_length=3, max_length=500, description="Question about the product catalog")
    tecnica: Literal["zero-shot", "few-shot", "cot"] = Field("zero-shot", description="Prompting technique to use")
    usar_rag: bool = Field(True, description="If true, retrieve matching products and add them as context")


class AIRespuesta(BaseModel):
    """LLM answer plus the data needed to audit and cost the call."""
    respuesta: str = Field(..., description="Answer generated by the LLM")
    modelo: str = Field(..., description="Model that produced the answer")
    tecnica: str = Field(..., description="Prompting technique that was used")
    usar_rag: bool = Field(..., description="Whether catalog products were added as context")
    productos_contexto: List[int] = Field(..., description="Ids of the products sent as context")
    tokens_entrada: int = Field(..., description="Input (prompt) tokens billed")
    tokens_salida: int = Field(..., description="Output (answer) tokens billed")
    tokens_razonamiento: int = Field(..., description="Reasoning (thinking) tokens, if the model used any")
    latencia_ms: float = Field(..., description="Time taken by the LLM call, in milliseconds")

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "respuesta": "2 laptops and 3 mouse cost $5135000 in total.",
                "modelo": "gemini-3.5-flash-lite",
                "tecnica": "cot",
                "usar_rag": True,
                "productos_contexto": [1, 2],
                "tokens_entrada": 132,
                "tokens_salida": 207,
                "tokens_razonamiento": 0,
                "latencia_ms": 1443.2,
            }
        }
    )
