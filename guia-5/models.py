from typing import List, Literal

from pydantic import BaseModel, Field   


class ProductoBase(BaseModel):
    """Campos comunes para crear o actualizar un producto."""
    nombre: str = Field(..., min_length=1, description="Nombre del producto (obligatorio)")
    categoria: str = Field(..., min_length=1, description="Categoría del producto")
    precio: float = Field(..., gt=0, description="Precio del producto (debe ser mayor que 0)")
    stock: int = Field(..., ge=0, description="Cantidad disponible (no puede ser negativa)")


class ProductoCrear(ProductoBase):
    """Datos requeridos para crear un producto. El id lo asigna el cliente."""
    id: int = Field(..., description="Identificador único del producto")


class ProductoActualizar(ProductoBase):
    """Datos para actualizar un producto existente (no incluye id, viene en la URL)."""
    pass


class Producto(ProductoBase):
    """Representación completa de un producto almacenado."""
    id: int



class AIConsulta(BaseModel):
    pregunta: str = Field(..., min_length=3, max_length=500, description="Question about the product catalog")
    tecnica: Literal["zero-shot", "few-shot", "cot"] = Field("zero-shot", description="Prompting technique to use")
    usar_rag: bool = Field(True, description="If true, retrieve matching products and add them as context")


class AIRespuesta(BaseModel):
    respuesta: str = Field(..., description="Answer generated by the LLM")
    modelo: str = Field(..., description="Model that produced the answer")
    tecnica: str
    usar_rag: bool
    productos_contexto: List[int] = Field(..., description="Ids of the products sent as context")
    tokens_entrada: int
    tokens_salida: int
    tokens_razonamiento: int
    latencia_ms: float